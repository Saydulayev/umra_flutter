/// Конфигурация для системы оценки приложения
/// Основана на лучших практиках Google Play и Apple App Store
class ReviewConfig {
  ReviewConfig._();

  // ========== РЕЖИМ РАБОТЫ ==========
  /// Переключите на true для тестирования, false для продакшена
  static const bool isTestMode = false; // ПРОДАКШЕН РЕЖИМ

  // ========== ПРОДАКШЕН КОНФИГУРАЦИЯ ==========

  /// Минимальное время использования приложения перед показом диалога (в секундах)
  /// Рекомендация: 3-5 минут активного использования
  /// Это гарантирует, что пользователь достаточно ознакомился с приложением
  static int get minUsageTimeSeconds =>
      isTestMode ? 30 : 180; // 30 сек для теста, 3 минуты для продакшена

  /// Минимальное количество запусков приложения перед показом диалога
  /// Рекомендация: минимум 3-5 запусков
  /// Это показывает, что пользователь регулярно использует приложение
  static int get minAppLaunches =>
      isTestMode ? 1 : 3; // 1 для теста, 3 для продакшена

  /// Минимальное количество дней с первого запуска
  /// Рекомендация: минимум 1-2 дня
  /// Пользователь должен использовать приложение хотя бы несколько дней
  static int get minDaysSinceFirstLaunch =>
      isTestMode ? 0 : 1; // 0 для теста, 1 для продакшена

  /// Интервал между показами диалога (в днях)
  /// Рекомендация: 90-180 дней (3-6 месяцев)
  /// Google рекомендует не показывать чаще раза в 3 месяца
  /// Apple рекомендует не чаще раза в год
  /// Мы используем 90 дней как баланс между получением отзывов и не надоеданием пользователями
  static int get daysBetweenPrompts =>
      isTestMode ? 0 : 90; // 0 для теста (каждый раз), 90 для продакшена

  /// Максимальное количество показов диалога за все время
  /// Рекомендация: максимум 3-5 раз за все время использования приложения
  /// После этого прекращаем показывать, чтобы не раздражать пользователя
  static int get maxTotalPrompts =>
      isTestMode ? 10 : 3; // 10 для теста, 3 для продакшена

  // ========== ТЕСТОВАЯ КОНФИГУРАЦИЯ ==========
  /// Для тестирования используйте эти значения:
  /// static const int minUsageTimeSeconds = 30; // 30 секунд
  /// static const int minAppLaunches = 1;
  /// static const int minDaysSinceFirstLaunch = 0;
  /// static const int daysBetweenPrompts = 0; // Показывать каждый раз
  /// static const int maxTotalPrompts = 10;
}
