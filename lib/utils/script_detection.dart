/// Буквы, которые есть в урду, но не используются в арабском тексте
/// (ٹ ڈ ڑ ں ھ ہ ۂ ۃ ی ے ۓ ک گ پ چ ژ).
///
/// Нужны, чтобы экраны, которые ищут «длинные арабские строки» по диапазону
/// U+0600–U+06FF, не принимали прозу на урду за дуа/аят и не рисовали её
/// в рамке ArabicTextWidget. В арабских текстах приложения этих символов нет,
/// поэтому для арабского и остальных языков поведение не меняется.
const Set<int> _urduOnlyLetters = {
  0x0679, // ٹ
  0x0688, // ڈ
  0x0691, // ڑ
  0x06BA, // ں
  0x06BE, // ھ
  0x06C1, // ہ
  0x06C2, // ۂ
  0x06C3, // ۃ
  0x06CC, // ی
  0x06D2, // ے
  0x06D3, // ۓ
  0x06A9, // ک
  0x06AF, // گ
  0x067E, // پ
  0x0686, // چ
  0x0698, // ژ
};

bool containsUrduLetters(String s) => s.runes.any(_urduOnlyLetters.contains);
